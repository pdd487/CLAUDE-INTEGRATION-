#!/usr/bin/env node
/*
 * Builds base-bench-standalone.html: the whole app in one file, fonts included
 * as data URIs. Save it anywhere, open it in a browser, and it runs — no
 * server, no network, no other files.
 *
 *   node build-standalone.cjs
 */

const fs = require("fs");
const path = require("path");

const DIR = __dirname;
const OUT = path.join(DIR, "base-bench-standalone.html");

function fail(msg) {
  console.error("build-standalone: " + msg);
  process.exit(1);
}

// Swap each font file reference for the file itself, base64'd inline.
function inlineFonts() {
  const css = fs.readFileSync(path.join(DIR, "fonts", "fonts.css"), "utf8");
  let count = 0;

  const out = css.replace(/url\('\.\/([^']+\.woff2)'\)/g, function (_, file) {
    const abs = path.join(DIR, "fonts", file);
    if (!fs.existsSync(abs)) fail("missing font file " + file);
    count++;
    return "url(data:font/woff2;base64," + fs.readFileSync(abs).toString("base64") + ")";
  });

  if (count === 0) fail("no font URLs found in fonts/fonts.css");
  console.log("  inlined " + count + " font references");
  return out;
}

// Drop anything that points at a file we are not shipping.
function strip(html, needle, label) {
  if (html.indexOf(needle) === -1) fail("could not find " + label + " to remove");
  return html.replace(needle, "");
}

let html = fs.readFileSync(path.join(DIR, "index.html"), "utf8");

html = strip(html, '<link rel="manifest" href="./manifest.webmanifest">\n', "manifest link");
html = strip(html, '<link rel="icon" href="./icon-192.png" type="image/png">\n', "icon link");
html = strip(html, '<link rel="apple-touch-icon" href="./icon-180.png">\n', "apple-touch-icon link");

// The service worker needs a real server; a standalone file is already offline.
const SW_BLOCK = html.match(/\n<script>\n\/\/ Cache the app[\s\S]*?<\/script>\n/);
if (!SW_BLOCK) fail("could not find the service worker registration to remove");
html = html.replace(SW_BLOCK[0], "");

const FONT_LINK = '<link rel="stylesheet" href="./fonts/fonts.css">';
if (html.indexOf(FONT_LINK) === -1) fail("could not find the font stylesheet link");
html = html.replace(FONT_LINK, "<style>\n" + inlineFonts() + "</style>");

html = html.replace(
  "<title>Base Bench</title>",
  "<title>Base Bench</title>\n<!-- Generated by build-standalone.cjs - edit index.html, not this file. -->"
);

fs.writeFileSync(OUT, html);
console.log("  wrote " + path.basename(OUT) + " (" + Math.round(html.length / 1024) + " KB)");
